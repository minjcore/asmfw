def parse(path):
    text = open(path).read()
    src = text.split('\n')
    o = {'file': path, 'lines': text.count('\n'), 'banner': [], 'code': [],
         'data': [], 'consts': [], 'macros': []}

    for l in src[:40]:
        if l.startswith(';'):
            s = l.lstrip(';').strip()
            if s and not set(s) <= set('=- '):
                o['banner'].append(s)
        elif l.strip() == '' and o['banner']:
            break

    pend = None
    for i, l in enumerate(src, 1):
        m = re.match(r'^;\s*([a-z_][a-z0-9_]*)\s+--\s*(.*)$', l)
        if m:
            pend = [m.group(1), m.group(2).strip(), False]
            continue
        m = re.match(r'^;\s+(\S.*)$', l)                 # tiếp dòng của header
        if m and pend:
            t = m.group(1).strip()
            if set(t) <= set('=- '):                     # dòng kẻ kết thúc header
                pend[2] = True
            elif not pend[2]:
                pend[1] = (pend[1] + ' ' + t).strip()
            continue
        m = re.match(r'^([a-z_][a-z0-9_]*):', l)
        if m:
            n = m.group(1)
            doc = pend[1] if pend and pend[0] == n else ''
            rest = re.sub(r';.*$', '', l[len(n) + 1:]).strip()
            j = i
            while not rest and j < len(src):
                cand = re.sub(r';.*$', '', src[j]).strip()
                if cand and not re.match(r'^(align|global)\b', cand):
                    rest = cand
                j += 1
            kind = 'data' if re.match(r'^(d[bwdq]\b|times\b)', rest) else 'code'
            o[kind].append({'n': n, 'l': i, 'doc': doc})
            pend = None
            continue
        m = re.match(r'^([A-Z_][A-Z0-9_]*)\s+equ\s', l)
        if m:
            o['consts'].append(m.group(1))
        m = re.match(r'^%macro\s+(\S+)', l)
        if m:
            o['macros'].append(m.group(1))
    return o


# --- gom file theo cây ------------------------------------------------------
TREES = [
    ('src',          sorted(glob.glob('src/*.asm')) + sorted(glob.glob('src/*.inc'))),
    ('kernel',       sorted(glob.glob('kernel/*.asm')) + sorted(glob.glob('kernel/*.inc'))),
    ('kernel/progs', sorted(glob.glob('kernel/progs/*'))),
    ('payload',      ['payload/hello.asm']),
]

ALLFILES = [p for _, fs in TREES for p in fs]
P = {p: parse(p) for p in ALLFILES}


def group_of(path):
    d = os.path.dirname(path)
    return d if d else '.'


# Bảng symbol theo từng cây, để cái tên kbd_* trùng nhau không sinh cạnh ảo.
def defmap(files):
    d = {}
    for p in files:
        for s in P[p]['code'] + P[p]['data']:
            d.setdefault(s['n'], p)
    return d


SCOPE = {}
for p in ALLFILES:
    g = group_of(p)
    if g == 'src':
        SCOPE[p] = defmap([x for x in ALLFILES if group_of(x) == 'src'])
    elif g == 'kernel':
        SCOPE[p] = defmap([x for x in ALLFILES if group_of(x) == 'kernel'])
    else:                                    # program: chỉ thấy chính nó + ulib
        SCOPE[p] = defmap(['kernel/progs/ulib.inc', p])

deps = defaultdict(lambda: defaultdict(set))
rdeps = defaultdict(lambda: defaultdict(set))
for p in ALLFILES:
    for m in re.finditer(r'(?m)^\s+(?:call|jmp)\s+(?:strict\s+\w+\s+)?([a-z_][a-z0-9_]*)\b',
                         open(p).read()):
        h = SCOPE[p].get(m.group(1))
        if h and h != p:
            deps[p][h].add(m.group(1))
            rdeps[h][p].add(m.group(1))


def dash(t):
    return re.sub(r'(?<= )--(?= )', '\u2014', t)


def summary(o, limit=330):
    b = o['banner']
    if not b:
        return ('', '')
    first = b[0]
    first = first.split('--', 1)[1].strip() if '--' in first else first
    body = dash(' '.join(b[1:]))
    if len(body) > limit:
        cut = body[:limit]
        stop = cut.rfind('. ')
        body = cut[:stop + 1] if stop > 80 else cut.rstrip(' ,;') + '.'
    return (first[0].upper() + first[1:] if first else '', body)


def docpath(src_path, out):
    """src/acpi.asm -> <out>/src/acpi.md"""
    d, base = os.path.split(src_path)
    return os.path.join(out, d, os.path.splitext(base)[0] + '.md')


def up(from_doc, to_repo_path):
    """Đường dẫn tương đối từ một file doc về một đường dẫn trong repo."""
    return os.path.relpath(to_repo_path, os.path.dirname(from_doc))


def emit_module(p, L):
    o = P[p]
    out = docpath(p, L['out'])
    os.makedirs(os.path.dirname(out), exist_ok=True)
    head, body = summary(o)
    w = ['# %s\n' % os.path.basename(p)]
    w.append('[`%s`](%s) — %d %s, %d %s.\n'
             % (p, up(out, p), o['lines'], L['lines'], len(o['code']), L['eps']))
    if head:
        w.append('\n%s.\n' % head.rstrip('.'))
    if body:
        w.append('\n%s\n' % body)

    if o['code']:
        w.append('\n## %s\n' % L['h_ep'])
        w.append('\n| %s | %s | %s |\n| --- | --- | --- |\n'
                 % (L['c_name'], L['c_line'], L['c_contract']))
        for c in o['code']:
            w.append('| `%s` | [%d](%s#L%d) | %s |\n'
                     % (c['n'], c['l'], up(out, p), c['l'],
                        dash(c['doc']).replace('|', '\\|') or '—'))

    if o['macros'] or o['consts'] or o['data']:
        w.append('\n## %s\n' % L['h_def'])
        if o['macros']:
            w.append('\n%s: %s\n' % (L['macros'], ', '.join('`%s`' % m for m in o['macros'])))
        if o['consts']:
            w.append('\n%s: %d.\n' % (L['consts'], len(o['consts'])))
        if o['data']:
            ds = o['data'][:18]
            more = L['more'] % (len(o['data']) - 18) if len(o['data']) > 18 else ''
            w.append('\n%s: %s%s\n'
                     % (L['data'], ', '.join('`%s`' % d['n'] for d in ds), more))

    d, r = deps.get(p), rdeps.get(p)
    if d or r:
        w.append('\n## %s\n' % L['h_dep'])
        for label, edges in ((L['calls'], d), (L['called'], r)):
            if not edges:
                continue
            w.append('\n%s:\n\n' % label)
            for k, v in sorted(edges.items()):
                w.append('- [%s](%s) — %s\n'
                         % (os.path.basename(k), up(out, docpath(k, L['out'])),
                            ', '.join('`%s`' % x for x in sorted(v))))

    w.append('\n---\n\n%s\n' % L['footer'])
    open(out, 'w').write(''.join(w))


def emit_index(L):
    w = ['# %s\n\n' % L['title']] + L['intro']
    w.append('```\npython3 docs/generate.py\npython3 docs/verify.py\n```\n')
    total = 0
    for group, files in TREES:
        title, blurb = L['trees'][group]
        w.append('\n## %s\n\n%s\n\n' % (title, blurb))
        w.append('| %s | %s | %s | %s |\n| --- | --- | --- | --- |\n'
                 % (L['c_file'], L['lines'].capitalize(), L['eps'].capitalize(), L['c_about']))
        for p in files:
            o = P[p]
            head, _ = summary(o)
            rel = os.path.relpath(docpath(p, L['out']), L['out'])
            w.append('| [%s](%s) | %d | %d | %s |\n'
                     % (os.path.basename(p), rel, o['lines'],
                        len(o['code']), head.rstrip('.')))
            total += 1
        w.append('\n')
    w.append('---\n\n' + L['outro'] % total)
    open(os.path.join(L['out'], 'README.md'), 'w').write(''.join(w))


for code, L in LANGS.items():
    if os.path.isdir(L['out']):
        shutil.rmtree(L['out'])          # file source bị xoá thì doc cũng phải mất
    os.makedirs(L['out'], exist_ok=True)
    for p in ALLFILES:
        emit_module(p, L)
    emit_index(L)
    print('%s: %d module trong %s' % (code, len(ALLFILES), L['out']))

print('%d cạnh phụ thuộc' % sum(len(v) for v in deps.values()))
