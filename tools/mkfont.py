# ------------------------------------------------------------------ emit


def cell(ch):
    rows = [0] * 16
    art = G.get(ch)
    if art is None:
        return rows
    for i, line in enumerate(art):
        bits = 0
        for x, c in enumerate(line):
            if c == '#':
                bits |= 1 << (6 - x)      # columns 1..6, MSB leftmost
        rows[BODY_TOP + i] = bits
    return rows


def render(ch):
    out = []
    for b in cell(ch):
        out.append(''.join('#' if b & (1 << (7 - x)) else '.' for x in range(8)))
    return out


